export function currentLanguage(): Language {
  return localStorage.getItem('averis-language') === 'en' ? 'en' : 'id';
}

export function switchLanguage(language: Language) {
  localStorage.setItem('averis-language', language);
  window.location.reload();
}

function translateNode(node: Text) {
  const raw = node.nodeValue ?? '';
  const trimmed = raw.trim();
  if (!trimmed) return;
  const translated = dictionary[trimmed];
  if (translated) node.nodeValue = raw.replace(trimmed, translated);
}

function translateElement(root: ParentNode) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node: Node | null;
  while ((node = walker.nextNode())) {
    const parent = node.parentElement;
    if (parent && !['SCRIPT', 'STYLE'].includes(parent.tagName)) translateNode(node as Text);
  }
  root.querySelectorAll?.('input[placeholder]').forEach((element) => {
    const input = element as HTMLInputElement;
    if (dictionary[input.placeholder]) input.placeholder = dictionary[input.placeholder];
  });
}

export function initLanguage() {
  if (currentLanguage() !== 'id') return;
  const apply = () => translateElement(document.body);
  apply();
  const observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      mutation.addedNodes.forEach((node) => {
        if (node.nodeType === Node.TEXT_NODE) translateNode(node as Text);
        else if (node.nodeType === Node.ELEMENT_NODE) translateElement(node as Element);
      });
    }
  });
  observer.observe(document.body, { childList: true, subtree: true });
}
